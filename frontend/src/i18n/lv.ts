/** The shape every language dictionary has. */
export type Dict = typeof lv

function copy<T>(value: T): T {
  if (typeof value !== 'object' || value === null) return value
  return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, copy(item)])) as T
}

/**
 * The live strings the UI reads (`t.section.key`). A language switch copies another dictionary into this same object
 * graph (i18n/language.ts), so module-level references such as `const tc = t.capabilities` stay valid.
 */
export const t: Dict = copy(lv)

export function errorMessage(error: unknown): string {
  const code = typeof error === 'object' && error && 'code' in error ? String(error.code) : ''
  return t.errors[code] ?? t.app.errors[code] ?? t.errors.generic
}
